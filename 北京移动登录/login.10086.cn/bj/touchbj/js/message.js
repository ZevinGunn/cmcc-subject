/** 根据Error Code 获取 信息**/
function getMessage($code) {
  var tt = "";
  $code = $.trim($code);
  if ($code == "") {
    return "";
  }
  // Jquery 遍历
  $.each(JSONMessage, function (k, v) {
    if ($code == k) {
      tt = v;
    }
  });
  return tt;
}
